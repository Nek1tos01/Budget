test('округление распределённого чека меняет сумму выбранной категории', async ({ page }) => {
  test.setTimeout(60_000)
  await start(page)
  const tab = (name: string) => page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
  await tab('Настройки')
  const toggle = page.getByRole('switch', { name: 'Округлять суммы чеков вверх' })
  await toggle.click()
  await expect(toggle).toBeChecked()
  await tab('Бюджет')
  await openReceipt(page)
  await choose(page, 'Сканировать QR-код')
  await dialog(page).getByText('Вставить строку QR-кода', { exact: true }).click()
  await dialog(page).getByLabel('Строка QR-кода').fill(fiscalQr.replace('2847.50', '28.42'))
  await choose(page, 'Прочитать QR-код')
  await dialog(page).getByLabel('Магазин').fill('Распределённый чек')
  await choose(page, 'Добавить товары')
  for (const [name, amount, category] of [['Молоко', '20', 'Продукты'], ['Хлеб', '8,42', 'Кафе']]) {
    await choose(page, 'Добавить товар')
    await dialog(page).getByLabel('Название товара').fill(name)
    await dialog(page).getByLabel('Стоимость позиции, ₽').fill(amount)
    await choose(page, 'Сохранить товар')
    await dialog(page).getByRole('button', { name: `Категория для ${name}` }).click()
    await chooseCategory(page, category)
  }
  await choose(page, 'Продолжить')
  await choose(page, 'По категориям')
  const roundedCategory = dialog(page).getByLabel('Категория округления')
  await expect(roundedCategory.locator('option:checked')).toHaveText('Продукты')
  await roundedCategory.selectOption({ label: 'Кафе' })
  const roundingRow = dialog(page).getByText('Округление чека', { exact: true }).locator('../..')
  await expect(roundingRow).toContainText('Кафе')
  await expect(roundingRow).toContainText('+0,58 ₽')
  await checkWidths(page, 'Сохранить чек')
  await choose(page, 'Сохранить чек')
  await choose(page, 'Посмотреть в истории')
  const row = page.getByRole('button', { name: /Распределённый чек/ })
  await expect(row).toContainText('29 ₽')
  await expect(row).toContainText('28,42 ₽')
  await page.getByRole('button', { name: 'Фильтры операций' }).click()
  await page.getByRole('combobox', { name: 'Категория', exact: true }).selectOption({ label: 'Кафе' })
  await expect(row).toContainText('−9 ₽')
  await expect(row).toContainText('−8,42 ₽')
  await row.click()
  await expect(roundingRow).toContainText('Кафе')
  await expect(roundingRow).toContainText('+0,58 ₽')
  await choose(page, 'Редактировать')
  await choose(page, 'Продолжить')
  await roundedCategory.selectOption({ label: 'Продукты' })
  await choose(page, 'Сохранить изменения')
  await expect(dialog(page).getByText('Изменить округление чека?')).toBeVisible()
  await choose(page, 'Подтвердить изменение')
  await expect(roundingRow).toContainText('Продукты')
})

