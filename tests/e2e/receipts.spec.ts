test('QR без фото сохраняет одну операцию и отклоняет повторный импорт', async ({ page }) => {
  await start(page)
  for (let run = 0; run < 2; run++) {
    await openReceipt(page)
    await choose(page, 'Сканировать QR-код')
    await dialog(page).getByText('Вставить строку QR-кода', { exact: true }).click()
    await dialog(page).getByLabel('Строка QR-кода').fill(fiscalQr)
    await choose(page, 'Прочитать QR-код')
    if (run === 0) {
      await expect(dialog(page).getByLabel('Итог чека, ₽')).toHaveValue('2847,5')
      await choose(page, 'Выбрать категорию расхода')
      await chooseCategory(page, 'Продукты')
      await choose(page, 'Сохранить чек')
      await choose(page, 'Вернуться в бюджет')
    }
  }
  await expect(dialog(page).getByText('Этот чек уже добавлен.')).toBeVisible()
  await choose(page, 'Открыть добавленный чек')
  await expect(dialog(page).getByText('Сумма по QR-коду').locator('..')).toContainText('2 847,50 ₽')
  await expect(dialog(page).getByText('Учтено в бюджете').locator('..')).toContainText('2 847,50 ₽')
  await expect(dialog(page).getByRole('heading', { name: /Товары/ })).toHaveCount(0)
})

