import { mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import { expect, test, type Page } from '@playwright/test'
import { syntheticReceiptPhoto } from '../fixtures/receipt-photo'

const fiscalQr = 't=20261120T1742&s=2847.50&fn=000110000105&i=12345678&fp=123456&n=1'
const dialog = (page: Page) => page.getByRole('dialog')
const choose = (page: Page, name: string) => dialog(page).getByRole('button', { name, exact: true }).click()

async function openReceipt(page: Page) {
  await page.getByRole('button', { name: 'Добавить операцию', exact: true }).click()
  await choose(page, 'Чек')
}

async function start(page: Page) {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Открыть демо-бюджет' }).click()
  await expect(page.getByRole('heading', { name: 'Бюджет', exact: true })).toBeVisible()
}

async function chooseCategory(page: Page, category: string) {
  await dialog(page).getByRole('textbox', { name: 'Поиск категорий' }).fill(category)
  await choose(page, category)
  await choose(page, 'Применить')
}

async function checkWidths(page: Page, primaryAction: string) {
  for (const width of [320, 375, 390, 430]) {
    await page.setViewportSize({ width, height: 844 })
    await expect(dialog(page).getByRole('button', { name: primaryAction, exact: true })).toBeInViewport()
    expect(await dialog(page).evaluate(sheet => {
      const content = sheet.querySelector('.sheet-content')!
      const root = document.documentElement
      return root.scrollWidth <= root.clientWidth && sheet.scrollWidth <= sheet.clientWidth && content.scrollWidth <= content.clientWidth
    })).toBe(true)
  }
}

